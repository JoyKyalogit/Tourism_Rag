const FALLBACK_IMAGE =
  "https://upload.wikimedia.org/wikipedia/commons/8/83/Nairobi_skyline_P1000019.jpg";

export function lookupDestinationImages(name) {
  const key = name.toLowerCase().trim();
  const entry = DESTINATION_IMAGES[key];
  if (!entry) {
    return { image: FALLBACK_IMAGE, gallery: [FALLBACK_IMAGE] };
  }
  return {
    image: entry.image,
    gallery: entry.gallery?.length ? entry.gallery : [entry.image],
  };
}
